"""Writes public/images/qr.svg, the deck URL's QR code, from its module grid.

The grid encodes HTTPS://PYCONES2026.EMBEDDEDLOG.COM (version 2-M, 25 modules).
If data-deck-url changes, paste a new grid from any QR encoder ('#' dark,
'.' light) and rerun: python3 scripts/art/qr.py
"""

from pathlib import Path

URL = "https://pycones2026.embeddedlog.com"

GRID = """
#######.##..##.#..#######
#.....#..###.##...#.....#
#.###.#.#....##.#.#.###.#
#.###.#.......##..#.###.#
#.###.#..#.#.#....#.###.#
#.....#.###....##.#.....#
#######.#.#.#.#.#.#######
.........#..#..##........
#.#...##.#.#....#..#..#.#
#.#.#..##.##.#....##.#..#
...######...#..#..###.#.#
######.....##.##..#..#..#
#..#####..###.###.#.####.
.....#..#...#..#.##.##..#
##..#####...##..#.##.#.#.
...#.#.#.####.#..###...#.
##.##.#...#.#..######..##
........#....####...#####
#######.#.####..#.#.#.##.
#.....#..#....###...####.
#.###.#..#.##.#######.###
#.###.#...#.....#....#.#.
#.###.#.#.....#####.#####
#.....#..##.#.#.#..##.#.#
#######.##.###.####.#####
""".split()

OUT = Path(__file__).resolve().parents[2] / "public" / "images" / "qr.svg"


def runs(grid):
    """Each row's dark modules as runs, in one path so abutting cells leave no seams."""
    parts = []
    for y, row in enumerate(grid):
        x = 0
        while x < len(row):
            if row[x] == "#":
                start = x
                while x < len(row) and row[x] == "#":
                    x += 1
                parts.append(f"M{start} {y}h{x - start}v1h-{x - start}z")
            else:
                x += 1
    return "".join(parts)


size = len(GRID)
assert all(len(row) == size for row in GRID), "every row needs as many modules as there are rows"

OUT.write_text(f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="100" height="100" role="img" aria-label="QR code: {URL}">
  <!--
    {URL}, upper-cased so it fits QR alphanumeric
    mode: version 2-M, {size} modules. Square cells in full-strength gold,
    since a projector and a phone at the back of the room need every bit of
    each cell's light. Light on dark (inverted); the board around it is the
    quiet zone. Generated by scripts/art/qr.py: change that, not this file.
  -->
  <path fill="var(--pcb-gold, #FDCA42)" d="{runs(GRID)}" />
</svg>
""")
print(f"wrote {OUT}")
